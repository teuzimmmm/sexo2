"""Generate design/tokens.css from design/tokens.json (approved values only).

python design/build_tokens.py           write tokens.css
python design/build_tokens.py --check   exit 1 if tokens.css is stale
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
UNICODE_LATIN = (
    "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, "
    "U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD"
)


def render(tokens: dict) -> str:
    approved = tokens["approved"]
    lines = ["/* Generated by design/build_tokens.py from tokens.json. Do not edit. */", ""]
    for font in approved["font"].values():
        lines += [
            "@font-face {",
            f'  font-family: "{font["family"]}";',
            "  font-style: normal;",
            "  font-display: swap;",
            f"  font-weight: {font['weights']};",
            f'  src: url("{font["file"]}") format("woff2-variations");',
            f"  unicode-range: {UNICODE_LATIN};",
            "}",
            "",
        ]
    native = approved["nativeFallback"]["family"]
    lines += [
        ":root {",
        f'  --s2-font-display: "{approved["font"]["display"]["family"]}", "{native}", sans-serif;',
        f'  --s2-font-text: "{approved["font"]["text"]["family"]}", "{native}", sans-serif;',
        f"  --s2-numeric-stats: {approved['numeric']['stats']};",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    expected = render(json.loads((HERE / "tokens.json").read_text(encoding="utf-8")))
    target = HERE / "tokens.css"
    if "--check" in sys.argv:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != expected:
            print("design/tokens.css is stale: run python design/build_tokens.py")
            return 1
        return 0
    target.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {target.relative_to(HERE.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
